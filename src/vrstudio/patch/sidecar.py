"""Sidecar metadata schema and JSON I/O.

A sidecar describes, per time segment, a *fixed* rectilinear viewport and the
inner rect (the person region to be regenerated by the external AI tool). The
outer ring of the viewport (everything outside `inner`) is the "margin" that
stays fixed on paste-back to anchor the seam.

`StillGeometry` is the single-frame variant for `flow = patchimg`: no fps and no
frame range, so it cannot reuse the frozen `clip.json`. It is written by extract
as `extracts/<version>/still.json` and is the only authority for patchimg's
geometry on paste-back.
"""

import json
from dataclasses import dataclass, field, asdict
from pathlib import Path

#: The image model's supported output ratio. The viewport must sit on it; the
#: crop is a perspective image, so this is a model constraint, not geometry.
STILL_RATIO = (16, 9)
STILL_RATIO_LABEL = "16:9"


@dataclass
class Viewport:
    yaw_deg: float
    pitch_deg: float
    fov_h_deg: float
    width: int
    height: int


@dataclass
class InnerRect:
    x: int
    y: int
    width: int
    height: int


@dataclass
class Segment:
    id: str
    frame_start: int
    frame_end: int  # inclusive
    viewport: Viewport
    inner: InnerRect


@dataclass
class Sidecar:
    erp_width: int
    erp_height: int
    fps: float
    segments: list = field(default_factory=list)
    version: int = 1


def sidecar_to_dict(s: Sidecar) -> dict:
    return asdict(s)


def sidecar_from_dict(d: dict) -> Sidecar:
    segs = []
    for sd in d["segments"]:
        segs.append(
            Segment(
                id=sd["id"],
                frame_start=sd["frame_start"],
                frame_end=sd["frame_end"],
                viewport=Viewport(**sd["viewport"]),
                inner=InnerRect(**sd["inner"]),
            )
        )
    return Sidecar(
        erp_width=d["erp_width"],
        erp_height=d["erp_height"],
        fps=d["fps"],
        segments=segs,
        version=d.get("version", 1),
    )


def save_sidecar(s: Sidecar, path):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(sidecar_to_dict(s), f, indent=2, ensure_ascii=False)


def load_sidecar(path) -> Sidecar:
    with open(path, "r", encoding="utf-8") as f:
        return sidecar_from_dict(json.load(f))


@dataclass
class StillGeometry:
    """patchimg 的单帧几何（``extracts/<版本>/still.json``）。

    erp 尺寸 + 视口 + inner 足以重建投影与贴回。构造即校验，让非法几何无法
    被写盘或被读到 merge：源不是 2:1、视口不是图片模型支持的 16:9、inner
    越出视口，三种情况都在这里报错。
    """

    erp_width: int
    erp_height: int
    viewport: Viewport
    inner: InnerRect
    version: int = 1

    def __post_init__(self):
        if self.version != 1:
            raise ValueError(f"still.json 只支持 version 1，读到 {self.version!r}")
        if self.erp_width <= 0 or self.erp_height <= 0:
            raise ValueError(
                f"erp 尺寸必须是正数：{self.erp_width}x{self.erp_height}")
        aspect = self.erp_width / self.erp_height
        if abs(aspect - 2.0) > 0.001:
            raise ValueError(
                f"源 ERP 必须是 2:1：{self.erp_width}x{self.erp_height}"
                f"（比例 {aspect:.4f}）")
        vp, inner = self.viewport, self.inner
        if vp.width <= 0 or vp.height <= 0:
            raise ValueError(f"视口尺寸必须是正数：{vp.width}x{vp.height}")
        want = STILL_RATIO[0] / STILL_RATIO[1]
        if abs(vp.width / vp.height - want) > want * 0.001:
            raise ValueError(
                f"视口 {vp.width}x{vp.height} 的比例是 "
                f"{vp.width / vp.height:.4f}，图片模型只支持 {STILL_RATIO_LABEL}")
        if inner.width <= 0 or inner.height <= 0:
            raise ValueError(f"inner 不能为空：{inner.width}x{inner.height}")
        if (inner.x < 0 or inner.y < 0
                or inner.x + inner.width > vp.width
                or inner.y + inner.height > vp.height):
            raise ValueError(
                f"inner {inner.x},{inner.y},{inner.width}x{inner.height} 越出 "
                f"{vp.width}x{vp.height} 视口")


def still_to_dict(g: StillGeometry) -> dict:
    return {
        "version": g.version,
        "erp_width": g.erp_width,
        "erp_height": g.erp_height,
        "viewport": asdict(g.viewport),
        "inner": asdict(g.inner),
    }


def still_from_dict(d: dict) -> StillGeometry:
    missing = [k for k in ("erp_width", "erp_height", "viewport", "inner")
               if k not in d]
    if missing:
        raise ValueError(f"still.json 缺字段：{', '.join(missing)}")
    return StillGeometry(
        erp_width=int(d["erp_width"]),
        erp_height=int(d["erp_height"]),
        viewport=Viewport(**d["viewport"]),
        inner=InnerRect(**d["inner"]),
        version=int(d.get("version", 0)),
    )


def save_still(g: StillGeometry, path) -> None:
    Path(path).write_text(
        json.dumps(still_to_dict(g), indent=2, ensure_ascii=False),
        encoding="utf-8")


def load_still(path) -> StillGeometry:
    return still_from_dict(json.loads(Path(path).read_text(encoding="utf-8")))
